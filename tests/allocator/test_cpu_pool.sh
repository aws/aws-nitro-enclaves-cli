# Unit tests for the CPU pool helpers in bootstrap/nitro-enclaves-allocator
# and bootstrap/nitro-cli-config. These tests only source the scripts; they do
# not need the Nitro Enclaves driver, root privileges or an EC2 instance.
#
# Usage: tests/allocator/test_cpu_pool.sh

SCRIPTDIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" >/dev/null 2>&1 && pwd)"
BOOTSTRAP="$SCRIPTDIR/../../bootstrap"
ALLOCATOR="$BOOTSTRAP/nitro-enclaves-allocator"
CLI_CONFIG="$BOOTSTRAP/nitro-cli-config"

# shellcheck source-path=SCRIPTDIR source=../../bootstrap/nitro-enclaves-allocator
source "$ALLOCATOR"

set -u

# The kernel stores ne_cpus in NE_CPUS_SIZE (512) bytes, NUL included.
NE_CPUS_MAX_LEN=511

passed=0
failed=0

function check {
    local name="$1"
    local actual="$2"
    local expected="$3"

    if [ "$actual" = "$expected" ]; then
        passed=$((passed + 1))
    else
        failed=$((failed + 1))
        echo "FAIL: $name"
        echo "  expected: '$expected'"
        echo "  actual:   '$actual'"
    fi
}

function check_compact {
    check "compact_cpu_list '$1'" "$(compact_cpu_list "$1")" "$2"
}

# Well-formed lists are compacted.
check_compact "1" "1"
check_compact "0-0" "0"
check_compact "3,1,2" "1-3"
check_compact "1,2,4,5,7" "1-2,4-5,7"
check_compact "5-7,1-3,4" "1-7"
check_compact "2,2,3" "2-3"
check_compact "1-10,3-5" "1-10"
check_compact "1-4,3-8" "1-8"
check_compact "1-2,3-4" "1-4"
check_compact "08,09" "8-9"
check_compact "2,3,6-9" "2-3,6-9"

# Whitespace is ignored (e.g. trailing spaces left in allocator.yaml).
check_compact "2,3,6-9 " "2-3,6-9"
check_compact " 2, 3 " "2-3"

# Malformed lists are passed through (whitespace removed) for the kernel to reject.
check_compact "" ""
check_compact "1,a" "1,a"
check_compact "7-3" "7-3"
check_compact "1,2," "1-2"
check_compact "1,,2" "1,,2"
check_compact "1-" "1-"
check_compact "-1" "-1"
check_compact "1-2-3" "1-2-3"

# Large ranges are not expanded CPU by CPU.
SECONDS=0
check_compact "0-1000000,5" "0-1000000"
check "large range is fast" "$((SECONDS < 2))" "1"

# Pool as generated by configure_cpu_pool_by_cpu_count() on an SMT host where
# the siblings of CPU N are N and N + 192, taking one NUMA node minus the core
# of CPU 0: 1,193,2,194,...,85,277.
smt_pool=""
for cpu in $(seq 1 85); do
    smt_pool="${smt_pool:+$smt_pool,}$cpu,$((cpu + 192))"
done
check "SMT pool exceeds ne_cpus limit uncompacted" "$((${#smt_pool} > NE_CPUS_MAX_LEN))" "1"
check_compact "$smt_pool" "1-85,193-277"

# Pool as generated on an SMT host with adjacent siblings (N, N + 1).
adjacent_pool="$(seq -s, 2 191)"
check "adjacent pool exceeds ne_cpus limit uncompacted" "$((${#adjacent_pool} > NE_CPUS_MAX_LEN))" "1"
check_compact "$adjacent_pool" "2-191"

# configure_cpu_pool() writes the compacted list to the CPU pool file.
tmp_dir="$(mktemp -d)"
trap 'rm -rf "$tmp_dir"' EXIT
CPU_POOL_FILE="$tmp_dir/ne_cpus"
VERBOSE="0"
touch "$CPU_POOL_FILE"
configure_cpu_pool "$smt_pool"
check "configure_cpu_pool writes compact pool" "$(cat "$CPU_POOL_FILE")" "1-85,193-277"

# configure_cpu_pool() fails, without writing, when even the compacted list
# does not fit in ne_cpus. Every other CPU from 100 to 400 compacts to 603
# characters.
fragmented_pool="$(seq -s, 100 2 400)"
echo "unchanged" > "$CPU_POOL_FILE"
too_long_output="$(configure_cpu_pool "$fragmented_pool" 2>&1)"
check "configure_cpu_pool rejects a too long pool" "$?" "1"
check "configure_cpu_pool reports the length" \
    "$([[ "$too_long_output" == *"603 characters"*"at most 511"* ]] && echo 1)" "1"
check "configure_cpu_pool does not write a too long pool" "$(cat "$CPU_POOL_FILE")" "unchanged"
configure_cpu_pool "$smt_pool"

# get_enclave_cpus() reads ranges back as individual CPUs.
check "get_enclave_cpus count" "$(get_enclave_cpus | wc -l)" "170"
check "get_enclave_cpus first" "$(get_enclave_cpus | head -1)" "1"
check "get_enclave_cpus last" "$(get_enclave_cpus | tail -1)" "277"

# nitro-cli-config carries its own copy of compact_cpu_list. It must match
# the allocator's, and it runs under "set -eu".
# shellcheck disable=SC2317 # Run in a subshell by cli_config.
function cli_config {
    (
        # nitro-cli-config returns early when sourced.
        # shellcheck source=/dev/null
        source "$CLI_CONFIG"
        trap - EXIT
        "$@"
    )
}
check "nitro-cli-config compact_cpu_list matches the allocator" \
    "$(cli_config declare -f compact_cpu_list)" \
    "$(declare -f compact_cpu_list)"
check "nitro-cli-config compacts under set -eu" \
    "$(cli_config compact_cpu_list "$smt_pool")" "1-85,193-277"
check "nitro-cli-config passes malformed lists through" \
    "$(cli_config compact_cpu_list "1,a")" "1,a"

# nitro-cli-config -p writes the compacted list to the CPU pool file.
cli_config_pool="$tmp_dir/cli_config_ne_cpus"
touch "$cli_config_pool"
(
    # shellcheck source=/dev/null
    source "$CLI_CONFIG"
    trap - EXIT
    # shellcheck disable=SC2317 # Called by configure_cpu_pool.
    function sudo_run { bash -c "$@"; }
    CPU_POOL_FILE="$cli_config_pool"
    configure_cpu_pool "$smt_pool"
)
check "nitro-cli-config writes compact pool" "$(cat "$cli_config_pool")" "1-85,193-277"

# nitro-cli-config also fails, without writing, on a too long pool.
echo "unchanged" > "$cli_config_pool"
(
    # shellcheck source=/dev/null
    source "$CLI_CONFIG"
    trap - EXIT
    # shellcheck disable=SC2317 # Called by configure_cpu_pool.
    function sudo_run { bash -c "$@"; }
    CPU_POOL_FILE="$cli_config_pool"
    configure_cpu_pool "$fragmented_pool"
) > /dev/null 2>&1
check "nitro-cli-config rejects a too long pool" "$?" "1"
check "nitro-cli-config does not write a too long pool" "$(cat "$cli_config_pool")" "unchanged"

echo "Passed: $passed, Failed: $failed"
[ "$failed" -eq 0 ]
